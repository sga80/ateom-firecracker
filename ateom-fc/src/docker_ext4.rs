pub fn setup_bundle_rootfs(root_fs_json: &str) -> anyhow::Result<(String, String)> {
    let file = File::open(root_fs_json)?;
    let reader = BufReader::new(file);
    let overlay_spec: OverlaySpec = serde_json::from_reader(reader)?;

    // check if the layer is finalized. if finalized, we don't to bundle as it is done already
    // each layer is a dir and there is a finalized file in it
    let mut lower_fs_dirs: Vec<String> = Vec::with_capacity(overlay_spec.layers.len());
    for layer_dir in &overlay_spec.layers {
        let finalized_maker = Path::new(&layer_dir).join("finalized");
        if !finalized_maker.exists() {
            // if not finalized then go ahead with the next step
            // TODO: we need to handle whiteouts and opaque directories here . counter doesnt have it so ignoring that step now
            fs::write(&finalized_maker, "").context("writing finalized marker")?;
        }
        lower_fs_dirs.push(format!("{layer_dir}/fs"));
    }

    // overlayfs wants the top-most layer first; the spec lists layers
    // bottom-most first (manifest order).
    lower_fs_dirs.reverse();
    // drop duplicate lowerdirs, keeping the first (topmost) occurrence --
    // overlayfs rejects a mount listing the same lowerdir twice, and real
    // images do sometimes repeat identical layers.
    let mut seen = HashSet::new();
    lower_fs_dirs.retain(|p| seen.insert(p.clone()));

    let bundle_dir = Path::new(root_fs_json)
        .parent()
        .context("rootfs-overlay.json has no parent directory")?;
    let rootfs_path = bundle_dir.join("rootfs");
    fs::create_dir_all(&rootfs_path).context("creating bundle rootfs dir")?;
    let rootfs_path_str = rootfs_path
        .to_str()
        .context("bundle rootfs path is not valid UTF-8")?;

    // Detach anything stale mounted here by a previous attempt. Matches Go's
    // `_ = unix.Unmount(rootfs, unix.MNT_DETACH)`: any error (including
    // "nothing was mounted there") is tolerated, not just a specific one.
    let _ = unmount(rootfs_path_str, UnmountFlags::DETACH);

    // Mount a read-only overlay of just the lowerdirs: we only ever read
    // this directory afterward (to tar it into the firecracker image
    // drive), never write to it, so no upperdir/workdir is needed.
    let fs_fd = fsopen("overlay", FsOpenFlags::FSOPEN_CLOEXEC).context("fsopen overlay")?;
    for lower in &lower_fs_dirs {
        fsconfig_set_string(&fs_fd, "lowerdir+", lower.as_str())
            .with_context(|| format!("setting lowerdir+ {lower}"))?;
    }
    fsconfig_create(&fs_fd).context("creating overlay superblock")?;

    let mount_fd = fsmount(&fs_fd, FsMountFlags::FSMOUNT_CLOEXEC, MountAttrFlags::empty())
        .context("fsmount overlay")?;
    move_mount(
        &mount_fd,
        "",
        CWD,
        rootfs_path_str,
        MoveMountFlags::MOVE_MOUNT_F_EMPTY_PATH,
    )
        .context("attaching overlay at bundle rootfs")?;

    Ok((rootfs_path_str.to_string(), overlay_spec.image_digest))
}
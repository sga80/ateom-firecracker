#[derive(Debug, Deserialize)]
pub struct OverlaySpec {
    pub version: u32,
    #[serde(rename = "imageDigest", default)]
    pub image_digest: String,
    /// Cached layer directories, bottom-most layer first (manifest order).
    /// Each holds its unpacked tree under `<dir>/fs/`.
    pub layers: Vec<String>,
    #[serde(rename = "extraDirs", default)]
    pub extra_dirs: Vec<String>,
    #[serde(rename = "imageVolumes", default)]
    pub image_volumes: Vec<ImageVolumeOverlay>,
}

/// Mirrors Go's `imagecache.ImageVolumeOverlay` -- one image-typed volume's
/// contents, composed the same way as the main rootfs but at its own
/// bundle-local mount point.
#[derive(Debug, Deserialize)]
pub struct ImageVolumeOverlay {
    pub name: String,
    #[serde(rename = "imageDigest", default)]
    pub image_digest: String,
    pub layers: Vec<String>,
}

pub fn docker_lower_ext4_block_device(path_to_flattened_docker_image: &str, image_digest: &str) -> anyhow::Result<String> {
    // takes the path on host and converts into a tar and then converts into a ext4 block device
    // first tar with tar
    //
    // Keyed by the image digest, not the actor: every actor running the same
    // image produces an identical composed rootfs, so the digest is the
    // natural cache key. For now we always rebuild -- no skip-if-exists yet.
    let safe_digest = image_digest.replace(':', "_");
    let out_path_str = format!("/run/ateomfc/image/{safe_digest}.ext4");
    let output_path = Path::new(&out_path_str);
    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)?;
    }
    let tar_output_path_str = format!("/tmp/{safe_digest}.tar");
    let tar_output_path = Path::new(&tar_output_path_str);
    if let Some(parent) = tar_output_path.parent() {
        fs::create_dir_all(parent)?;
    }
    let tar_file = File::create(tar_output_path)?;
    let mut tar = tar::Builder::new(tar_file);
    tar.follow_symlinks(false); // do not follow symlinks as these are docker images
    tar.append_dir_all("", path_to_flattened_docker_image)?;
    tar.finish()?;

    let tar_reader = File::open(tar_output_path)?;

    let mut formatter = Formatter::new(output_path, 4096, 128 * 1024 * 1024)
        .context("creating ext4 formatter")?;
    formatter
        .unpack_tar(tar_reader)
        .context("unpacking tar into ext4 image")?;
    formatter.close().context("closing ext4 formatter")?;

    println!("wrote ext4 image to {}", output_path.display());
    Ok(out_path_str)
}

pub fn docker_upper_ext4_block_device(actor_id: String) -> anyhow::Result<(String)> {
    let out_path_str = format!("/run/ateomfc/{actor_id}/upper.ext4");
    let output_path = Path::new(&out_path_str);
    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)?;
    }
    let formatter = Formatter::new(output_path, 4096, 128 * 1024 * 1024)
        .context("creating ext4 formatter")?;
    formatter.close().context("closing ext4 formatter")?;
    Ok(out_path_str)
}

